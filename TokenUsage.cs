using OutSystems.ExternalLibraries.SDK;

namespace VertexAILibrary
{
    /// <summary>
    /// Token counts for a single model call, normalised across publishers.
    /// </summary>
    [OSStructure(Description = "Token counts for a single model call.")]
    public struct TokenUsage
    {
        [OSStructureField(Description = "Tokens in the input prompt (excluding cached tokens for Anthropic models).")]
        public int InputTokens { get; set; }

        [OSStructureField(Description = "Tokens generated by the model.")]
        public int OutputTokens { get; set; }

        [OSStructureField(Description = "Total tokens billed for the call (input + output, including cache and thinking tokens).")]
        public int TotalTokens { get; set; }

        [OSStructureField(Description = "Input tokens served from the prompt cache (Anthropic only, 0 for Google).")]
        public int CachedInputTokens { get; set; }

        [OSStructureField(Description = "Input tokens written to the prompt cache (Anthropic only, 0 for Google).")]
        public int CacheCreationInputTokens { get; set; }

        [OSStructureField(Description = "Thinking tokens (Google only, 0 for Anthropic, where they are already included in OutputTokens).")]
        public int ThinkingTokens { get; set; }
    }
}
